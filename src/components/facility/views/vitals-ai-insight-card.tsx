"use client";

import { useEffect, useState } from "react";
import { NoticeSlot, useNotice } from "@/components/shared/inline-notice";
import { api } from "@/lib/api";
import { Card } from "@/components/ui/card";
import { SectionHeading } from "@/components/shared/section-heading";
import { Button } from "@/components/ui/button";
import { Sparkles, Loader2 } from "lucide-react";

/** Hakeem Insight's read of the patient's recorded vitals — split out of
 * VitalsPanel so callers can place it independently in the page flow (e.g.
 * after a Red Flag screening section) instead of always directly under the
 * KPI grid. */
export function VitalsAiInsightCard({
  patientId, apiClient = api, insightPath, visitId,
}: {
  patientId: string;
  /** Defaults to the facility `api` client; admin passes `adminApi` (same shape, different auth header). */
  apiClient?: { get?: <T = any>(url: string) => Promise<T>; post: <T = any>(url: string, body?: any) => Promise<T> };
  /** Defaults to the facility-scoped vitals-insight route; admin passes its own cross-facility route. */
  insightPath?: string;
  /** The visit currently being reviewed — when set (and insightPath isn't
   * overridden), the generated insight is persisted against it and reloaded
   * on mount, instead of being ephemeral/regenerate-only. */
  visitId?: string;
}) {
  const [insight, setInsight] = useState<string | null>(null);
  const [insightState, setInsightState] = useState<"idle" | "loading" | "not_configured" | "no_data">("idle");
  const msg = useNotice();

  useEffect(() => {
    if (!visitId || insightPath || !apiClient.get) return;
    apiClient.get<{ insight: string | null }>(`/api/facility/patients/${patientId}/vitals-insight?visitId=${visitId}`)
      .then((res) => { if (res.insight) setInsight(res.insight); })
      .catch(() => {});
  }, [patientId, visitId, insightPath, apiClient]);

  const getInsight = async () => {
    setInsightState("loading");
    msg.clear();
    try {
      const path = insightPath || `/api/facility/patients/${patientId}/vitals-insight`;
      const body = !insightPath && visitId ? { visitId } : {};
      const res = await apiClient.post<{ insight: string | null; reason?: string }>(path, body);
      if (res.insight) {
        setInsight(res.insight);
        setInsightState("idle");
      } else {
        setInsightState(res.reason === "not_configured" ? "not_configured" : "no_data");
      }
    } catch (e: any) {
      msg.error("Hakeem Insight couldn't read the vitals just now", `${e.message || "Network error"}.`, { retry: getInsight, retryLabel: "Try again" });
      setInsightState("idle");
    }
  };

  return (
    <Card className="p-4 gap-2 border-primary/20 bg-primary/5">
      <SectionHeading
        icon={Sparkles}
        title="Hakeem Insight"
        right={
          <Button size="sm" variant="outline" onClick={getInsight} disabled={insightState === "loading"}>
            {insightState === "loading" ? <Loader2 className="h-3.5 w-3.5 animate-spin" /> : <Sparkles className="h-3.5 w-3.5" />} Get Hakeem Insight
          </Button>
        }
      />
      {insight && <p className="text-sm mt-2 leading-relaxed">{insight}</p>}
      {insightState === "not_configured" && <p className="text-xs text-muted-foreground mt-2">Hakeem Insight isn&apos;t configured for this portal yet.</p>}
      {insightState === "no_data" && <p className="text-xs text-muted-foreground mt-2">Not enough recorded vitals to generate an insight.</p>}
      {insight && <p className="text-[10px] text-muted-foreground mt-2 italic">Generated by Hakeem Insight from recorded vitals — decision support only, not a diagnosis.</p>}
      <NoticeSlot state={msg} className="mt-2" />
    </Card>
  );
}
